def Level_Up(player):
  xp_needed = player.level*5 - 2
  if player.xp >= xp_needed:
    player.level += 1
    player.min_damage += 2
    player.max_damage += 3
    player.max_hp += 10
    player.hp = player.max_hp
    print(f"{player.name} leveled up! They are now level {player.level} and have been fully healed!\n")
    player.xp -= xp_needed
  else:
    print(f"{player.name} needs {xp_needed - player.xp} more XP to reach level {player.level + 1} \n")
  time.sleep(1)

def Combat(player, mob):
  while player.hp > 0 and mob.hp >0:
    choice = input("Choose an action:\n1.Attack\n2.Heal\n3.Run\n4.Inspect\n")
    if choice == '1':
      player_damage = player.attack()
      mob.hp -= player_damage
      print(f"{player.name} hits {mob.name} for {player_damage} damage!")
      print(f"{mob.name} HP: {max(0, mob.hp)}\n")
      time.sleep(.4)

      if mob.hp <= 0:
        break
      mob_damage = mob.attack()
      player.hp -= mob_damage
      print(f"{mob.name} hits {player.name} for {mob_damage} damage")
      print(f"{player.name} HP: {max(0,player.hp)}\n")
      time.sleep(.4)

    elif choice =='2':
      player.hp = min(player.max_hp, player.hp+10)
      print(f"{player.name} heals for 10 HP!")
      print(f"{player.name} HP: {player.hp}\n")

      mob_damage = mob.attack()
      player.hp -= mob_damage
      print(f"{mob.name} hits {player.name} for {mob_damage} damage")
      print(f"{player.name} HP: {max(0,player.hp)}\n")
      time.sleep(.4)

    elif choice == "3":
      print("You ran away and escaped the dungeon.")
      return "Ran_away"

    elif choice == "4":
      print(f"Monster: {mob.name}\nMonster HP: {mob.hp}\nMonster Type: {mob.mob_type}")

    else:
      print("Please input a valid option.")

  if player.hp > 0:
    print(f"{player.name} defeated the {mob.name}!")
    player.xp += mob.xp_reward
    print(f"{player.name} gained {mob.xp_reward} XP!")
    print(f"{player.name} now has a total of {player.xp} XP.")
    Level_Up(player)
    return "Victory"
  else:
    print(f"{player.name} was defeated!")
    return "Defeat"

def Spawn_Mob():
  monsters = [
    ("Goblin", 10, 1, 5, 1,"Humanoid"),
    ("Wolf", 15, 2, 6, 1, "Beast"),
    ("Bandit", 20, 3, 5, 2, "Humanoid"),
    ("Rat", 10, 2, 5, 1, "Beast")
  ]
  monster = random.choice(monsters)
  return Mob(*monster)

def Spawn_Boss():
  bosses = [
    ("Bandit Leader", 45, 3, 9, 4,"Humanoid"),
    ("Alpha Wolf", 35, 4, 10, 4, "Beast"),
    ("Goblin Leader", 35, 2, 8, 4, "Humanoid")
  ]
  boss = random.choice(bosses)
  return Mob(*boss)

def Loot_Drop():
  loot_table = [
      Item("Sharp Stick", "Weapon", min_dmg_bonus=1),
      Item("Rusty Sword", "Weapon", min_dmg_bonus=2, max_dmg_bonus=3),
      Item("Paper Hat", "Helmet", hp_bonus=1),
      Item("Thin Shirt", "Chest", hp_bonus=2),
      Item("Mocassins", "Boots", hp_bonus=1)
  ]


  if random.random() < 0.25:
    return random.choice(loot_table)
  return None

def Handle_Loot(player,mob):
  loot = Loot_Drop()
  if loot:
    print(f"The {mob.name} dropped a {loot.name}!")
    choice = input("Equip it? Y or N\n").lower()
    if choice == "y":
      player.equip(loot)
    else:
      player.inventory.append(loot)
      print(f"{loot.name} was added to your inventory.")

