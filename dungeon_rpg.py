#Object Creation
#Character
class Character:
  def __init__(self,name,player_class):
    self.name = name
    self.player_class = player_class
    self.level = 1
    self.xp = 0
    self.max_hp = 50
    self.hp = self.max_hp
    self.min_damage = 1
    self.max_damage = 10
    self.inventory = []
    self.equipment = {
      "Weapon": None,
      "Helmet": None,
      "Chest": None,
      "Boots": None
      }
    self.gold = 0
  def attack(self):
    return random.randint(self.min_damage, self.max_damage)

  def equip(self, item):
    old_item = self.equipment[item.slot]
    if old_item:
      self.max_hp -= old_item.hp_bonus
      self.min_damage -= old_item.min_dmg_bonus
      self.max_damage -= old_item.max_dmg_bonus
    self.equipment[item.slot] = item
    self.max_hp += item.hp_bonus
    self.min_damage += item.min_dmg_bonus
    self.max_damage += item.max_dmg_bonus
    print(f"{self.name} equipped {item.name}!")

#Monster
class Mob:
  def __init__(self, name, hp, min_damage, max_damage, xp_reward, mob_type):
    self.name = name
    self.mob_type = mob_type
    self.hp = hp
    self.min_damage = min_damage
    self.max_damage = max_damage
    self.xp_reward = xp_reward
  def attack(self):
    return random.randint(self.min_damage, self.max_damage)

#Equipment
class Item:
  def __init__(self, name, slot, hp_bonus=0, min_dmg_bonus=0, max_dmg_bonus=0):
    self.name = name
    self.slot = slot
    self.hp_bonus = hp_bonus
    self.min_dmg_bonus = min_dmg_bonus
    self.max_dmg_bonus = max_dmg_bonus

